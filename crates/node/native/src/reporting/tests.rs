/// The fixture's block with a coinbase in its diff: a block with a
/// transaction, as `Mina_block.transactions` counts them. Only the diff
/// changes; nothing here checks the block's hash or proof.
fn block_with_coinbase(fixture: &Fixture) -> ArcBlockWithHash {
    let mut block = fixture.block();
    let diff = &mut block.body.staged_ledger_diff.diff.0;
    diff.coinbase = v2::StagedLedgerDiffDiffPreDiffWithAtMostTwoCoinbaseStableV2Coinbase::One(None);
    diff.internal_command_statuses = [v2::MinaBaseTransactionStatusStableV2::Applied]
        .into_iter()
        .collect();
    BlockWithHash::try_new(Arc::new(block)).unwrap()
}

/// A job of the block's own ledger statement, as the node would name it.
fn transition_job(block: &ArcBlockWithHash, zkapp: bool) -> RpcReportingUptimeJob {
    let statement = &block
        .header()
        .protocol_state
        .body
        .blockchain_state
        .ledger_proof_statement;
    RpcReportingUptimeJob::Transition {
        pair: (&statement.source, &statement.target).into(),
        index: 1,
        zkapp,
    }
}

/// A `Proof_data` of the dummy transaction proof, for its layout.
fn proof_data(block: &ArcBlockWithHash) -> ProofData {
    let statement = &block
        .header()
        .protocol_state
        .body
        .blockchain_state
        .ledger_proof_statement;
    ProofData {
        proof: v2::LedgerProofProdStableV2(v2::TransactionSnarkStableV2 {
            statement: v2::MinaStateSnarkedLedgerStateWithSokStableV2 {
                source: statement.source.clone(),
                target: statement.target.clone(),
                connecting_ledger_left: statement.connecting_ledger_left.clone(),
                connecting_ledger_right: statement.connecting_ledger_right.clone(),
                supply_increase: statement.supply_increase.clone(),
                fee_excess: statement.fee_excess.clone(),
                sok_digest: vec![7; 32].into(),
            },
            proof: v2::dummy_transaction_proof().into(),
        }),
        proof_time: 12.5,
        snark_work_fee: v2::CurrencyFeeStableV1(
            v2::UnsignedExtendedUInt64Int64ForVersionTagsStableV1(4_000_000u64.into()),
        ),
    }
}

/// OCaml's order: no transactions sends the block alone whatever the jobs;
/// then a job list that can't be had skips; then no jobs, or no matching
/// Transition, sends the block alone; a match is proved.
#[test]
fn best_tip_work_follows_ocaml_cases_in_order() {
    let fixture = Fixture::load("devnet");
    let empty = fixture.arc_block();
    let full = block_with_coinbase(&fixture);
    // The captured blocks have no transactions: OCaml sent them alone.
    assert_eq!(uptime_work::has_transactions(&empty), Ok(false));
    assert_eq!(uptime_work::has_transactions(&full), Ok(true));
    let jobs = [
        None,
        Some(RpcReportingUptimeJob::Unavailable("missing state".into())),
        Some(RpcReportingUptimeJob::NoJobs),
        Some(RpcReportingUptimeJob::NoMatchingTransition),
        Some(transition_job(&full, false)),
    ];
    for job in &jobs {
        assert_eq!(
            uptime_work::best_tip_work(&empty, job.as_ref()),
            BestTipWork::BlockOnly(uptime_work::NO_TRANSACTIONS)
        );
    }
    let [none, unavailable, no_jobs, no_match, transition] = jobs.each_ref();
    assert!(matches!(
        uptime_work::best_tip_work(&full, none.as_ref()),
        BestTipWork::Skip(_)
    ));
    assert_eq!(
        uptime_work::best_tip_work(&full, unavailable.as_ref()),
        BestTipWork::Skip("could not get the SNARK work: missing state".into())
    );
    assert_eq!(
        uptime_work::best_tip_work(&full, no_jobs.as_ref()),
        BestTipWork::BlockOnly(uptime_work::NO_JOBS)
    );
    assert_eq!(
        uptime_work::best_tip_work(&full, no_match.as_ref()),
        BestTipWork::BlockOnly(uptime_work::NO_MATCHING_TRANSITION)
    );
    let statement = &full
        .header()
        .protocol_state
        .body
        .blockchain_state
        .ledger_proof_statement;
    assert_eq!(
        uptime_work::best_tip_work(&full, transition.as_ref()),
        BestTipWork::Prove(UptimeJob {
            pair: (&statement.source, &statement.target).into(),
            index: 1,
            zkapp: false,
        })
    );
}

/// `Proof_data` is written unversioned: the ledger proof, the proof time
/// as an 8-byte little-endian float of seconds, then the fee. The OCaml
/// bytes are checked in `full_proof_captures_match_ocaml_byte_for_byte`.
#[test]
fn proof_data_is_its_three_fields_in_order() {
    let fixture = Fixture::load("devnet");
    let data = proof_data(&fixture.arc_block());
    let encoded = STANDARD.decode(data.to_base64().unwrap()).unwrap();
    let mut expected = Vec::new();
    data.proof.binprot_write(&mut expected).unwrap();
    expected.extend(12.5f64.to_le_bytes());
    data.snark_work_fee.binprot_write(&mut expected).unwrap();
    assert_eq!(encoded, expected);
    let decoded = <ProofData as mina_p2p_messages::binprot::BinProtRead>::binprot_read(
        &mut encoded.as_slice(),
    )
    .unwrap();
    assert_eq!(decoded, data);
}

/// A prover answering `outcome`, recording what it was asked; `None` never
/// answers.
struct TestProver {
    outcome: Option<ProofOutcome>,
    requests: Mutex<Vec<UptimeProofRequest>>,
}

impl uptime_work::UptimeProver for TestProver {
    fn prove(&self, request: UptimeProofRequest) -> futures::future::BoxFuture<'_, ProofOutcome> {
        self.requests.lock().unwrap().push(request);
        let outcome = self.outcome.clone();
        Box::pin(async move {
            match outcome {
                Some(outcome) => outcome,
                None => futures::future::pending().await,
            }
        })
    }
}

/// One best-tip iteration with a transaction, `job` and a prover answering
/// `outcome`, signed by a key made here.
async fn work_iteration(
    test: &str,
    job: RpcReportingUptimeJob,
    outcome: Option<ProofOutcome>,
    interrupt: Interruptor,
) -> (
    Vec<Record>,
    visibility::ReporterStatus,
    Arc<TestProver>,
    ArcBlockWithHash,
) {
    let fixture = Fixture::load("devnet");
    let receiver = Receiver::start(test, "200", "0");
    let block = block_with_coinbase(&fixture);
    let snapshot = RpcReportingSnapshot {
        best_tip: Some(block.clone()),
        uptime_spec: None,
        snark_work_fee: None,
        uptime_job: Some(job),
        ..fixture_snapshot(&fixture)
    };
    let ctx = test_ctx(180_000, fixture.network.clone(), None);
    let status = ctx.status.clone();
    let prover = Arc::new(TestProver {
        outcome,
        requests: Default::default(),
    });
    let reporter = UptimeReporter {
        shared: shared(ScriptedSource::new([Some(snapshot)]), ctx),
        prover: prover.clone(),
        config: UptimeConfig {
            snark_work_fee: v2::CurrencyFeeStableV1(100_000_000u64.into()),
            url: receiver.url("/v1/submit"),
            submitter: AccountSecretKey::rand(),
            send_commit_sha: false,
            dry_run_dir: None,
        },
    };
    reporter.iteration(0, interrupt).await;
    let records = receiver.records();
    (records, status.get().uptime.unwrap(), prover, block)
}

