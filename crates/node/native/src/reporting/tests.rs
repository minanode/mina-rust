fn fixtures_dir() -> PathBuf {
    Path::new(env!("CARGO_MANIFEST_DIR")).join("../../../tools/uptime-fixtures")
}

struct Fixture {
    network: NetworkId,
    /// The exact HTTP body OCaml sent.
    request: Vec<u8>,
    /// Its exact signed `data` substring.
    data: Vec<u8>,
    manifest: serde_json::Value,
    /// Generated by OCaml for the capture; never funded, never reused.
    key: AccountSecretKey,
}

impl Fixture {
    fn load(name: &str) -> Self {
        let dir = fixtures_dir().join("fixtures").join(name);
        let read = |file: &str| std::fs::read(dir.join(file)).unwrap();
        let manifest: serde_json::Value = serde_json::from_slice(&read("manifest.json")).unwrap();
        let key: serde_json::Value =
            serde_json::from_slice(&read("THROWAWAY-TEST-KEY.json")).unwrap();
        Self {
            network: match manifest["network"].as_str().unwrap() {
                "mainnet" => NetworkId::MAINNET,
                "devnet" => NetworkId::TESTNET,
                other => panic!("{other}"),
            },
            request: read("uptime-1.json"),
            data: read("uptime-data.json"),
            manifest,
            key: key["private_key_base58"].as_str().unwrap().parse().unwrap(),
        }
    }

    fn request_json(&self) -> serde_json::Value {
        serde_json::from_slice(&self.request).unwrap()
    }

    fn data_field(&self, key: &str) -> Option<String> {
        self.request_json()["data"][key].as_str().map(str::to_owned)
    }

    fn block_bytes(&self) -> Vec<u8> {
        STANDARD.decode(self.data_field("block").unwrap()).unwrap()
    }

    fn block(&self) -> v2::MinaBlockBlockStableV2 {
        uptime::decode_block(&self.block_bytes()).unwrap()
    }

    fn arc_block(&self) -> ArcBlockWithHash {
        BlockWithHash::try_new(Arc::new(self.block())).unwrap()
    }

    /// The data as this code builds it from the block, not the captured
    /// string: the block re-encoded from its decoded form.
    fn rebuilt_data(&self) -> BlockData {
        BlockData {
            block: uptime::encode_block_base64(&self.block()).unwrap(),
            created_at: self.data_field("created_at").unwrap(),
            peer_id: self.data_field("peer_id").unwrap(),
            snark_work: None,
            graphql_control_port: None,
            built_with_commit_sha: self.data_field("built_with_commit_sha"),
        }
    }

    fn other_network(&self) -> NetworkId {
        match self.network {
            NetworkId::MAINNET => NetworkId::TESTNET,
            NetworkId::TESTNET => NetworkId::MAINNET,
        }
    }

    /// `created_at` as milliseconds, for a fixed clock.
    fn created_at_ms(&self) -> u64 {
        let text = self.data_field("created_at").unwrap();
        let t = time::OffsetDateTime::parse(&text, &time::format_description::well_known::Rfc3339)
            .unwrap();
        (t.unix_timestamp() as u64) * 1000
    }
}

