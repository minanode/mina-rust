/// Answers with scripted snapshots, the last repeated.
struct ScriptedSource {
    snapshots: Mutex<VecDeque<Option<RpcReportingSnapshot>>>,
    calls: std::sync::atomic::AtomicUsize,
}

impl ScriptedSource {
    fn new(snapshots: impl IntoIterator<Item = Option<RpcReportingSnapshot>>) -> Self {
        Self {
            snapshots: Mutex::new(snapshots.into_iter().collect()),
            calls: Default::default(),
        }
    }
}

impl SnapshotSource for ScriptedSource {
    fn snapshot(
        &self,
        _watch: Option<RpcReportingProducedBlockWatch>,
    ) -> futures::future::BoxFuture<'_, Option<RpcReportingSnapshot>> {
        self.calls.fetch_add(1, std::sync::atomic::Ordering::SeqCst);
        let mut queue = self.snapshots.lock().unwrap();
        let next = if queue.len() > 1 {
            queue.pop_front().unwrap()
        } else {
            queue.front().cloned().flatten()
        };
        Box::pin(async move { next })
    }
}

