/// Check the actual signed requests from an isolated dry-run node. Full
/// blockchain/proof/SOK verification is additionally run with OCaml.
#[test]
#[ignore = "requires a completed devnet dry-run report directory"]
fn uptime_dry_run_signatures_and_targets() {
    use ledger::scan_state::transaction_logic::{signed_command::Body, Transaction, UserCommand};
    use mina_p2p_messages::binprot::BinProtRead;
    mina_core::NetworkConfig::init("devnet").unwrap();
    let directory = std::env::var_os("MINA_UPTIME_DRY_RUN_REPORTS").expect("report directory");
    let mut count = 0;
    let mut work = 0;
    let mut coinbase_only = 0;
    let mut payment = 0;
    for entry in std::fs::read_dir(directory).unwrap() {
        let path = entry.unwrap().path();
        if path.extension().and_then(|s| s.to_str()) != Some("json") {
            continue;
        }
        let bytes = std::fs::read(&path).unwrap();
        uptime::verify_request(&bytes, NetworkId::TESTNET).unwrap();
        let json: serde_json::Value = serde_json::from_slice(&bytes).unwrap();
        let block = uptime::decode_block(
            &STANDARD
                .decode(json["data"]["block"].as_str().unwrap())
                .unwrap(),
        )
        .unwrap();
        let block = BlockWithHash::try_new(Arc::new(block)).unwrap();
        if let Some(encoded) = json["data"]["snark_work"].as_str() {
            let raw = STANDARD.decode(encoded).unwrap();
            let mut cursor = raw.as_slice();
            let proof = ProofData::binprot_read(&mut cursor).unwrap();
            assert!(cursor.is_empty());
            assert_eq!(
                proof.proof.0.statement.target.second_pass_ledger,
                block.staged_ledger_hashes().non_snark.ledger_hash
            );
            assert_eq!(
                proof.snark_work_fee,
                v2::CurrencyFeeStableV1(1_000_000u64.into())
            );
            assert!(proof.proof_time.is_finite() && proof.proof_time >= 0.0);
            let diff =
                ledger::staged_ledger::diff::Diff::try_from(&block.body().staged_ledger_diff)
                    .unwrap();
            let commands = diff.commands();
            let payments = commands.iter().filter(|command| matches!(&command.data,
                UserCommand::SignedCommand(command) if matches!(command.payload.body, Body::Payment(_)))).count();
            let consensus = block.consensus_state();
            let transactions = diff
                .get_transactions(
                    mina_core::constants::constraint_constants(),
                    (&consensus.coinbase_receiver).try_into().unwrap(),
                    consensus.supercharge_coinbase,
                )
                .unwrap();
            let coinbases = transactions
                .iter()
                .filter(|transaction| matches!(transaction.data, Transaction::Coinbase(_)))
                .count();
            coinbase_only += usize::from(commands.is_empty() && coinbases > 0);
            payment += usize::from(payments > 0);
            eprintln!("report height={} hash={} work=true user_commands={} payments={payments} coinbases={coinbases} proof_seconds={}",
                block.height(), block.hash(), commands.len(), proof.proof_time);
            work += 1;
        }
        count += 1;
    }
    assert!(count >= 8, "only {count} reports");
    assert!(work > 0);
    assert!(
        coinbase_only > 0 && payment > 0,
        "with work: {coinbase_only} coinbase-only, {payment} payment blocks"
    );
    eprintln!("{count} signatures verified; {work} work targets and fees checked; {coinbase_only} coinbase-only and {payment} payment blocks with work");
}

