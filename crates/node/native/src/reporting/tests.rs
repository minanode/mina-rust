/// `tools/uptime-fixtures/receiver.py` on a free loopback port, stopped by
/// its own PID when dropped.
struct Receiver {
    child: Child,
    port: u16,
    output: PathBuf,
    _dir: Option<tempfile::TempDir>,
}

#[derive(Debug, Clone)]
struct Record {
    at: f64,
    path: String,
    headers: Vec<(String, String)>,
    body: Vec<u8>,
    status: u16,
}

impl Receiver {
    fn start(test: &str, statuses: &str, delays: &str) -> Self {
        let (dir, output) = match std::env::var_os("R43E2_RECEIVER_DIR") {
            Some(dir) => {
                std::fs::create_dir_all(&dir).unwrap();
                let output = PathBuf::from(dir).join(format!("{test}.jsonl"));
                let _ = std::fs::remove_file(&output);
                (None, output)
            }
            None => {
                let dir = tempfile::TempDir::new().unwrap();
                let output = dir.path().join(format!("{test}.jsonl"));
                (Some(dir), output)
            }
        };
        let mut child = Command::new("python3")
            .arg("-I")
            .arg(fixtures_dir().join("receiver.py"))
            .args([
                "--port",
                "0",
                "--statuses",
                statuses,
                "--delays",
                delays,
                "--output",
            ])
            .arg(&output)
            .stdout(Stdio::piped())
            .stderr(Stdio::null())
            .spawn()
            .expect("python3 runs receiver.py");
        let mut line = String::new();
        BufReader::new(child.stdout.take().unwrap())
            .read_line(&mut line)
            .unwrap();
        let port = line
            .trim()
            .rsplit(':')
            .next()
            .and_then(|p| p.parse().ok())
            .unwrap_or_else(|| panic!("receiver said {line:?}"));
        Self {
            child,
            port,
            output,
            _dir: dir,
        }
    }

    fn url(&self, path: &str) -> reqwest::Url {
        format!("http://127.0.0.1:{}{path}", self.port)
            .parse()
            .unwrap()
    }

    fn records(&self) -> Vec<Record> {
        let Ok(text) = std::fs::read_to_string(&self.output) else {
            return Vec::new();
        };
        text.lines()
            .map(|line| {
                let v: serde_json::Value = serde_json::from_str(line).unwrap();
                Record {
                    at: v["received_at_unix"].as_f64().unwrap(),
                    path: v["path"].as_str().unwrap().to_owned(),
                    headers: v["headers"]
                        .as_array()
                        .unwrap()
                        .iter()
                        .map(|h| {
                            (
                                h[0].as_str().unwrap().to_lowercase(),
                                h[1].as_str().unwrap().to_owned(),
                            )
                        })
                        .collect(),
                    body: STANDARD.decode(v["body_base64"].as_str().unwrap()).unwrap(),
                    status: v["response_status"].as_u64().unwrap() as u16,
                }
            })
            .collect()
    }

    /// Waits until `n` records are written.
    async fn wait_for(&self, n: usize, timeout: Duration) -> Vec<Record> {
        let deadline = Instant::now() + timeout;
        loop {
            let records = self.records();
            if records.len() >= n || Instant::now() > deadline {
                return records;
            }
            tokio::time::sleep(Duration::from_millis(20)).await;
        }
    }
}

impl Drop for Receiver {
    fn drop(&mut self) {
        let _ = self.child.kill();
        let _ = self.child.wait();
    }
}

/// Waits until the recorded status satisfies `done`: the receiver writes
/// its record before it answers, so an outcome lands a moment later.
async fn wait_status(
    status: &StatusSink,
    timeout: Duration,
    done: impl Fn(&visibility::ReportingStatus) -> bool,
) -> visibility::ReportingStatus {
    let deadline = Instant::now() + timeout;
    loop {
        let now = status.get();
        if done(&now) || Instant::now() > deadline {
            return now;
        }
        tokio::time::sleep(Duration::from_millis(20)).await;
    }
}

fn header<'a>(record: &'a Record, name: &str) -> Option<&'a str> {
    record
        .headers
        .iter()
        .find(|(k, _)| k == name)
        .map(|(_, v)| v.as_str())
}

fn fast(max_attempts: u32) -> RetryPolicy {
    RetryPolicy {
        max_attempts,
        pause: Duration::from_millis(30),
    }
}

fn test_client(request: Duration) -> reqwest::Client {
    delivery::client(Timeouts {
        connect: Duration::from_secs(2),
        request,
    })
    .unwrap()
}

async fn send(
    client: &reqwest::Client,
    url: &reqwest::Url,
    body: &[u8],
    policy: RetryPolicy,
    interrupt: &Interruptor,
) -> (Delivery, Vec<Attempt>) {
    let mut attempts = Vec::new();
    let delivery = delivery::deliver(
        client,
        url,
        bytes::Bytes::copy_from_slice(body),
        policy,
        delivery::uptime_status_class,
        interrupt,
        &mut |_n: u32, a: &Attempt| attempts.push(a.clone()),
    )
    .await;
    (delivery, attempts)
}

#[tokio::test]
async fn uptime_success_sends_the_ocaml_bytes() {
    for name in ["mainnet", "devnet"] {
        let fixture = Fixture::load(name);
        let receiver = Receiver::start(&format!("success-{name}"), "200", "0");
        let request = UptimeRequest::create(
            fixture.rebuilt_data(),
            &fixture.key,
            fixture.network.clone(),
        );
        let (delivery, _) = send(
            &test_client(Duration::from_secs(10)),
            &receiver.url("/v1/submit"),
            request.body.as_bytes(),
            RetryPolicy::UPTIME,
            &Interruptor::new(),
        )
        .await;
        assert_eq!(delivery, Delivery::Delivered { attempts: 1 });
        let records = receiver.records();
        assert_eq!(records.len(), 1);
        let record = &records[0];
        assert_eq!(record.path, "/v1/submit");
        assert_eq!(
            record.body, fixture.request,
            "{name}: bytes as OCaml sent them"
        );
        assert_eq!(header(record, "content-type"), Some("application/json"));
        assert_eq!(
            header(record, "content-length"),
            Some(fixture.request.len().to_string().as_str())
        );
        // The receiver accepts it as OCaml's backend would check it.
        uptime::verify_request(&record.body, fixture.network.clone()).unwrap();
    }
}

/// The R43e.1 capture: OCaml retried 503, 503, 200 four seconds apart with
/// the same bytes (4.005953 s, 4.006854 s).
#[tokio::test]
async fn uptime_retries_like_the_ocaml_trace() {
    let fixture = Fixture::load("mainnet-retry");
    let trace: Vec<serde_json::Value> =
        std::fs::read_to_string(fixtures_dir().join("fixtures/mainnet-retry/requests.jsonl"))
            .unwrap()
            .lines()
            .map(|l| serde_json::from_str(l).unwrap())
            .filter(|v: &serde_json::Value| v["path"] == "/uptime")
            .take(3)
            .collect();
    let ocaml_gaps: Vec<f64> = trace
        .windows(2)
        .map(|w| {
            w[1]["received_at_unix"].as_f64().unwrap() - w[0]["received_at_unix"].as_f64().unwrap()
        })
        .collect();

    let receiver = Receiver::start("retry-503-503-200", "503,503,200", "0");
    let request = UptimeRequest::create(
        fixture.rebuilt_data(),
        &fixture.key,
        fixture.network.clone(),
    );
    let (delivery, attempts) = send(
        &test_client(Duration::from_secs(10)),
        &receiver.url("/uptime"),
        request.body.as_bytes(),
        RetryPolicy::UPTIME,
        &Interruptor::new(),
    )
    .await;
    assert_eq!(delivery, Delivery::Delivered { attempts: 3 });
    assert_eq!(
        attempts,
        vec![
            Attempt::Status(503),
            Attempt::Status(503),
            Attempt::Status(200)
        ]
    );
    let records = receiver.records();
    assert_eq!(
        records.iter().map(|r| r.status).collect::<Vec<_>>(),
        [503, 503, 200]
    );
    for (record, ocaml) in records.iter().zip(&trace) {
        assert_eq!(record.body, fixture.request, "every attempt the same bytes");
        assert_eq!(
            STANDARD
                .decode(ocaml["body_base64"].as_str().unwrap())
                .unwrap(),
            fixture.request
        );
    }
    for (gap, ocaml_gap) in records
        .windows(2)
        .map(|w| w[1].at - w[0].at)
        .zip(ocaml_gaps)
    {
        assert!((4.0..4.5).contains(&gap), "gap {gap}");
        assert!(
            (gap - ocaml_gap).abs() < 0.4,
            "gap {gap} vs OCaml {ocaml_gap}"
        );
        println!("retry gap {gap:.6} s, OCaml {ocaml_gap:.6} s");
    }
}

