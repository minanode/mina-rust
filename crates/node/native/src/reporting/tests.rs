/// Model completions at the RPC boundary with the same first-event latch as
/// the producer. Ordinary samples cannot arm, cancel or consume the waiter.
struct ProductionSource {
    snapshot: RpcReportingSnapshot,
    pending: Mutex<Option<mina_node::block_producer::UptimeProducedBlock>>,
    completions: Mutex<Vec<ArcBlockWithHash>>,
    fail_first_poll: AtomicBool,
}

impl SnapshotSource for ProductionSource {
    fn snapshot(
        &self,
        watch: Option<RpcReportingProducedBlockWatch>,
    ) -> BoxFuture<'_, Option<RpcReportingSnapshot>> {
        use RpcReportingProducedBlockWatch as Watch;
        let mut pending = self.pending.lock().unwrap();
        let mut snapshot = self.snapshot.clone();
        match watch {
            Some(Watch::Start { subscription }) => {
                *pending = Some(mina_node::block_producer::UptimeProducedBlock::new(
                    subscription,
                ));
            }
            Some(Watch::Cancel { subscription }) => {
                if pending
                    .as_ref()
                    .is_some_and(|p| p.subscription == subscription)
                {
                    *pending = None;
                }
            }
            None => {
                if let Some(waiter) = pending.as_mut() {
                    for block in self.completions.lock().unwrap().drain(..) {
                        waiter.complete(&block, self.snapshot.next_production_time.unwrap());
                        // The second completion wins the frontier, removing the
                        // first. The reporting event must still be the first.
                        snapshot.best_tip = Some(block);
                    }
                    if self.fail_first_poll.swap(false, Ordering::Relaxed) {
                        return Box::pin(async { None });
                    }
                }
            }
        }
        snapshot.produced_block = pending.as_ref().and_then(|waiter| {
            waiter
                .block
                .as_ref()
                .map(|(block, slot_time)| RpcReportingProducedBlock {
                    block: block.clone(),
                    slot_time: *slot_time,
                    subscription: waiter.subscription,
                })
        });
        Box::pin(async { Some(snapshot) })
    }
}

