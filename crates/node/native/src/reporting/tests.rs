/// A capture in `tools/uptime-fixtures/full-proof/`, with real block and
/// transaction proofs. Its submitter key was not kept: the signature is
/// checked with the public key, and its encoding by writing OCaml's own
/// signature back out.
struct FullProof {
    name: &'static str,
    request: Vec<u8>,
    data: Vec<u8>,
    manifest: serde_json::Value,
    decoded: serde_json::Value,
}

const FULL_PROOFS: [&str; 3] = [
    "devnet-581348-coinbase",
    "devnet-581351-signed",
    "devnet-581352-signed",
];

impl FullProof {
    fn load(name: &'static str) -> Self {
        let dir = fixtures_dir().join("full-proof").join(name);
        let read = |file: &str| std::fs::read(dir.join(file)).unwrap();
        Self {
            name,
            request: read("uptime-1.json"),
            data: read("uptime-data.json"),
            manifest: serde_json::from_slice(&read("manifest.json")).unwrap(),
            decoded: serde_json::from_slice(&read("decoded.json")).unwrap(),
        }
    }

    fn json(&self) -> serde_json::Value {
        serde_json::from_slice(&self.request).unwrap()
    }

    fn field(&self, key: &str) -> String {
        self.json()["data"][key].as_str().unwrap().to_owned()
    }

    fn block(&self) -> v2::MinaBlockBlockStableV2 {
        uptime::decode_block(&STANDARD.decode(self.field("block")).unwrap()).unwrap()
    }

    fn proof_data(&self) -> ProofData {
        let bytes = STANDARD.decode(self.field("snark_work")).unwrap();
        let mut rest = bytes.as_slice();
        let data = <ProofData as mina_p2p_messages::binprot::BinProtRead>::binprot_read(&mut rest)
            .unwrap();
        assert!(rest.is_empty(), "{}: bytes after Proof_data", self.name);
        data
    }

    fn created_at_ms(&self) -> u64 {
        let t = time::OffsetDateTime::parse(
            self.manifest["created_at"].as_str().unwrap(),
            &time::format_description::well_known::Rfc3339,
        )
        .unwrap();
        (t.unix_timestamp() as u64) * 1000
    }
}

/// Every field this node writes, against OCaml's bytes: the block re-encoded
/// from its decoded form, the data rebuilt in OCaml's order (with the
/// captured work), its digest, OCaml's signature verified with the
/// submitter's public key, and the whole request written back out from that
/// signature and submitter. `Proof_data` decodes and re-encodes exactly.
#[test]
fn full_proof_captures_match_ocaml_byte_for_byte() {
    for name in FULL_PROOFS {
        let capture = FullProof::load(name);
        let block = capture.block();
        let encoded = uptime::encode_block_base64(&block).unwrap();
        assert_eq!(encoded, capture.field("block"), "{name}: block");
        let block = BlockWithHash::try_new(Arc::new(block)).unwrap();
        assert_eq!(
            block.hash().to_string(),
            capture.manifest["state_hash"].as_str().unwrap(),
            "{name}: state hash"
        );
        assert_eq!(uptime_work::has_transactions(&block), Ok(true), "{name}");

        let proof = capture.proof_data();
        assert_eq!(
            proof.to_base64().unwrap(),
            capture.field("snark_work"),
            "{name}: Proof_data"
        );
        assert_eq!(
            proof.proof_time,
            capture.decoded["snark_work"]["proof_time_seconds"]
                .as_f64()
                .unwrap()
        );
        assert_eq!(proof.snark_work_fee.0 .0.as_u64(), 1_000_000);
        // The proved job ends at the block's ledger: the selection rule.
        assert_eq!(
            proof.proof.0.statement.target.second_pass_ledger,
            block.staged_ledger_hashes().non_snark.ledger_hash,
            "{name}: target ledger"
        );

        let data = BlockData {
            block: encoded,
            created_at: capture.field("created_at"),
            peer_id: capture.field("peer_id"),
            snark_work: Some(proof.to_base64().unwrap()),
            graphql_control_port: None,
            built_with_commit_sha: Some(uptime::short_commit(
                capture.manifest["source_commit"].as_str().unwrap(),
            )),
        };
        assert_eq!(
            data.signed_string().as_bytes(),
            capture.data,
            "{name}: data bytes"
        );
        assert_eq!(
            hex::encode(uptime::UptimeDigest::of_data(&capture.data).0),
            capture.manifest["data_blake2b_256_hex"].as_str().unwrap(),
            "{name}: digest"
        );
        let (verified, _) = uptime::verify_request(&capture.request, NetworkId::TESTNET).unwrap();
        assert_eq!(verified, data, "{name}: verified data");
        assert_eq!(
            uptime::verify_request(&capture.request, NetworkId::MAINNET),
            Err(UptimeVerifyError::Signature),
            "{name}: wrong domain"
        );

        let json = capture.json();
        let signature: v2::Signature = json["signature"].as_str().unwrap().parse().unwrap();
        let signature = mina_signer::Signature::try_from(&*signature).unwrap();
        use ledger::FpExt;
        assert_eq!(
            signature.rx.to_decimal(),
            capture.manifest["signature_field_decimal"]
                .as_str()
                .unwrap()
        );
        assert_eq!(
            signature.s.to_decimal(),
            capture.manifest["signature_scalar_decimal"]
                .as_str()
                .unwrap()
        );
        let submitter: mina_node::account::AccountPublicKey =
            json["submitter"].as_str().unwrap().parse().unwrap();
        let request = UptimeRequest::with_signature(data, signature, submitter);
        assert_eq!(
            request.body.as_bytes(),
            capture.request,
            "{name}: request bytes"
        );
    }
}

