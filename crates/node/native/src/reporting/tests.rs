/// `start` as the node runs it: the reporters on their own thread, sampling
/// through an `RpcSender` (here answered by a stand-in node), and the panic
/// hook's handoff to the error reporter. The only test that calls `start`:
/// the error reporter's handle is process-wide.
#[test]
fn start_runs_the_reporters_and_reports_the_first_panic() {
    use mina_node::core::channels::{mpsc, oneshot};
    use mina_node_common::rpc::{NodeRpcRequest, RpcSender};

    let fixture = Fixture::load("devnet");
    let snapshot = fixture_snapshot(&fixture);
    let (tx, mut rx) = mpsc::channel::<NodeRpcRequest>(16);
    let requests = Arc::new(std::sync::atomic::AtomicUsize::new(0));
    let counted = requests.clone();
    std::thread::spawn(move || {
        let runtime = tokio::runtime::Builder::new_current_thread()
            .enable_all()
            .build()
            .unwrap();
        runtime.block_on(async move {
            while let Some(request) = rx.recv().await {
                assert!(matches!(
                    request.req,
                    mina_node::rpc::RpcRequest::ReportingSnapshotGet { .. }
                ));
                counted.fetch_add(1, std::sync::atomic::Ordering::SeqCst);
                let responder = request
                    .responder
                    .downcast::<oneshot::Sender<RpcReportingSnapshot>>()
                    .expect("the reporters' response type");
                let _ = responder.send(snapshot.clone());
            }
        });
    });

    let receiver = Receiver::start("start", "200", "0");
    // 100 ms slots: uptime and status every 500 ms.
    let ctx = test_ctx(100, fixture.network.clone(), None);
    let status = ctx.status.clone();
    start(
        RpcSender::new(tx),
        ReportingConfig {
            uptime: Some(UptimeConfig {
                snark_work_fee: v2::CurrencyFeeStableV1(100_000_000u64.into()),
                url: receiver.url("/v1/submit"),
                submitter: fixture.key.clone(),
                send_commit_sha: false,
                dry_run_dir: None,
            }),
            node_status: Some(NodeStatusConfig {
                url: receiver.url("/node-status"),
            }),
            node_error: Some(NodeErrorConfig {
                url: receiver.url("/node-error"),
                contact_info: None,
            }),
        },
        ctx,
    )
    .unwrap();

    let runtime = tokio::runtime::Builder::new_current_thread()
        .enable_all()
        .build()
        .unwrap();
    let records = runtime.block_on(async {
        let deadline = Instant::now() + Duration::from_secs(10);
        loop {
            let records = receiver.records();
            let has = |path: &str| records.iter().any(|r| r.path == path);
            if (has("/v1/submit") && has("/node-status")) || Instant::now() > deadline {
                return records;
            }
            tokio::time::sleep(Duration::from_millis(50)).await;
        }
    });
    let uptime = records
        .iter()
        .find(|r| r.path == "/v1/submit")
        .expect("an uptime report");
    uptime::verify_request(&uptime.body, fixture.network.clone()).unwrap();
    assert!(records.iter().any(|r| r.path == "/node-status"));

    // The panic hook's call, from another thread; it waits for the report.
    std::thread::Builder::new()
        .name("r43e2-test".into())
        .spawn(|| report_panic("r43e2 test panic", "crates/x.rs:1:2", "r43e2-test"))
        .unwrap()
        .join()
        .unwrap();
    let errors: Vec<_> = receiver
        .records()
        .into_iter()
        .filter(|r| r.path == "/node-error")
        .collect();
    assert_eq!(errors.len(), 1, "reported before report_panic returned");
    let report: serde_json::Value = serde_json::from_slice(&errors[0].body).unwrap();
    assert_eq!(
        report["data"]["error"]["string"],
        "thread 'r43e2-test' panicked: r43e2 test panic"
    );
    // A later panic is counted, not reported.
    report_panic("again", "crates/x.rs:3:4", "r43e2-test");
    assert_eq!(
        status.get().node_error.unwrap().last_skip_reason.as_deref(),
        Some("a later panic: only the first is reported")
    );
    assert!(requests.load(std::sync::atomic::Ordering::SeqCst) >= 2);
}

