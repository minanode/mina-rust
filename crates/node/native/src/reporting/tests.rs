#[test]
fn ocaml_requests_verify_only_in_their_own_domain() {
    for name in FIXTURES {
        let fixture = Fixture::load(name);
        let (data, block) =
            uptime::verify_request(&fixture.request, fixture.network.clone()).unwrap();
        assert_eq!(data, fixture.rebuilt_data());
        assert_eq!(block, fixture.block());
        assert_eq!(
            uptime::verify_request(&fixture.request, fixture.other_network()),
            Err(UptimeVerifyError::Signature),
            "{name}: wrong domain"
        );
        // Our own signature in the other domain differs and doesn't verify
        // in this one.
        let other = UptimeRequest::create(
            fixture.rebuilt_data(),
            &fixture.key,
            fixture.other_network(),
        );
        assert_ne!(other.body.as_bytes(), fixture.request);
        assert_eq!(
            uptime::verify_request(other.body.as_bytes(), fixture.network.clone()),
            Err(UptimeVerifyError::Signature)
        );
    }
}

#[test]
fn changed_bodies_are_rejected() {
    for name in FIXTURES {
        let fixture = Fixture::load(name);
        let text = String::from_utf8(fixture.request.clone()).unwrap();
        let created_at = fixture.data_field("created_at").unwrap();
        let later = schedule::rfc3339(fixture.created_at_ms() + 1_000);
        let changes = [
            text.replace(&created_at, &later),
            {
                let peer_id = fixture.data_field("peer_id").unwrap();
                let mut other = peer_id.clone();
                let last = other.pop().unwrap();
                other.push(if last == 'a' { 'b' } else { 'a' });
                text.replace(&peer_id, &other)
            },
            // One block byte changed: the Base64 still decodes.
            {
                let mut block = fixture.block_bytes();
                block[100] ^= 1;
                text.replace(
                    &fixture.data_field("block").unwrap(),
                    &STANDARD.encode(block),
                )
            },
            // An optional field added.
            text.replace(
                "\"},\"signature\"",
                "\",\"graphql_control_port\":3085},\"signature\"",
            ),
        ];
        for changed in changes {
            assert_ne!(changed, text);
            assert_eq!(
                uptime::verify_request(changed.as_bytes(), fixture.network.clone()),
                Err(UptimeVerifyError::Signature),
                "{name}"
            );
        }
    }
}

/// The digest's 64 hex digits as the signed bytes, as `String_sign` signs.
#[derive(Clone)]
struct HexDigest(Vec<u8>);

impl mina_hasher::Hashable for HexDigest {
    type D = NetworkId;

    fn to_roinput(&self) -> mina_hasher::ROInput {
        mina_hasher::ROInput::new().append_bytes(&self.0)
    }

    fn domain_string(network_id: Self::D) -> Option<String> {
        <uptime::UptimeDigest as mina_hasher::Hashable>::domain_string(network_id)
    }
}

#[test]
fn hex_digest_signatures_are_rejected() {
    for name in FIXTURES {
        let fixture = Fixture::load(name);
        let digest = uptime::UptimeDigest::of_data(&fixture.data);
        let hex = HexDigest(hex::encode(digest.0).into_bytes());
        let mut signer = mina_signer::create_legacy::<HexDigest>(fixture.network.clone());
        // OCaml's signature is over the raw bytes, not the hex digits.
        let ocaml = UptimeRequest::create(
            fixture.rebuilt_data(),
            &fixture.key,
            fixture.network.clone(),
        );
        let pk = mina_signer::PubKey::from_address(&ocaml.submitter.to_string()).unwrap();
        assert!(!signer.verify(&ocaml.signature, &pk, &hex));
        // A hex-digest signature in an uptime envelope doesn't verify.
        let keypair = mina_signer::Keypair::from(fixture.key.clone());
        let hex_signature = signer.sign(&keypair, &hex, mina_signer::NonceMode::Legacy);
        let forged = String::from_utf8(fixture.request.clone()).unwrap().replace(
            fixture.request_json()["signature"].as_str().unwrap(),
            &v2::Signature::from(v2::MinaBaseSignatureStableV1::from(&hex_signature)).to_string(),
        );
        assert_eq!(
            uptime::verify_request(forged.as_bytes(), fixture.network.clone()),
            Err(UptimeVerifyError::Signature),
            "{name}"
        );
    }
}

#[test]
fn foreign_envelopes_are_rejected() {
    for name in FIXTURES {
        let fixture = Fixture::load(name);
        let request = fixture.request_json();
        // A signed envelope without a `data` object.
        let body = serde_json::json!({
            "version": 1,
            "payload": "e30=",
            "submitter": request["submitter"],
            "signature": { "field": "1", "scalar": "1" },
        });
        assert_eq!(
            uptime::verify_request(&serde_json::to_vec(&body).unwrap(), fixture.network.clone()),
            Err(UptimeVerifyError::Shape("no data object")),
            "{name}"
        );
        // A field/scalar signature object in an uptime envelope.
        let mut forged = request;
        forged["signature"] = serde_json::json!({ "field": "1", "scalar": "1" });
        assert_eq!(
            uptime::verify_request(
                &serde_json::to_vec(&forged).unwrap(),
                fixture.network.clone()
            ),
            Err(UptimeVerifyError::Shape("signature"))
        );
    }
}

