#!/usr/bin/env python3
"""Verify an OCaml 4.0.2 Mesa devnet dump and generate embedded zstd assets.

Usage: embed-devnet.py <dump>/circuit-blobs/4.0.2devnet
The dump may contain symlinks. The committed SHA-256 list is the authority.
"""
import hashlib
from pathlib import Path
import subprocess
import sys

ROOT = Path(__file__).resolve().parents[2]
PINS = ROOT / "tools/mesa-circuits/devnet-blobs.sha256"
OUT = ROOT / "crates/ledger/src/proofs/data/circuits/4.0.2devnet"
MODULE = ROOT / "crates/ledger/src/proofs/embedded_circuits.rs"


def main() -> None:
    if len(sys.argv) != 2:
        raise SystemExit(f"usage: {sys.argv[0]} <dump>/circuit-blobs/4.0.2devnet")
    source = Path(sys.argv[1])
    entries = [line.split() for line in PINS.read_text().splitlines()]
    if len(entries) != 24 or len({name for _, name in entries}) != 24:
        raise SystemExit("expected exactly 24 distinct SHA-256 entries")
    if {p.name for p in source.iterdir()} != {name for _, name in entries}:
        raise SystemExit("dump names do not match the SHA-256 manifest")
    verified = []
    for digest, name in entries:
        path = (source / name).resolve(strict=True)
        if hashlib.sha256(path.read_bytes()).hexdigest() != digest:
            raise SystemExit(f"SHA-256 mismatch: {name}")
        verified.append((digest, name, path))
    OUT.mkdir(parents=True, exist_ok=True)
    if {p.name for p in OUT.iterdir()} - {name + ".zst" for _, name, _ in verified}:
        raise SystemExit("unexpected file in embedded circuit directory")
    for digest, name, path in verified:
        compressed = subprocess.run(
            ["zstd", "-19", "-q", "-c", str(path)], check=True, capture_output=True
        ).stdout
        restored = subprocess.run(
            ["zstd", "-d", "-q", "-c"],
            input=compressed,
            check=True,
            capture_output=True,
        ).stdout
        if hashlib.sha256(restored).hexdigest() != digest:
            raise SystemExit(f"compressed round trip failed: {name}")
        (OUT / (name + ".zst")).write_bytes(compressed)
    lines = [
        "//! OCaml 4.0.2 Mesa devnet circuit blobs; generated by tools/mesa-circuits/embed-devnet.py.",
        "//! Digests are from tools/mesa-circuits/devnet-blobs.sha256.",
        "",
        "pub(super) fn get(name: &str) -> Option<(&'static [u8], &'static str)> {",
        "    match name {",
    ]
    for digest, name, _ in verified:
        lines += [
            f'        "{name}" => Some((',
            f'            include_bytes!("data/circuits/4.0.2devnet/{name}.zst"),',
            f'            "{digest}",',
            "        )),",
        ]
    lines += ["        _ => None,", "    }", "}", ""]
    MODULE.write_text("\n".join(lines))
    print(f"verified {len(verified)} files; wrote {sum(p.stat().st_size for p in OUT.glob('*.zst'))} compressed bytes")


if __name__ == "__main__":
    main()
