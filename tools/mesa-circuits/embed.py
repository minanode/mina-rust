#!/usr/bin/env python3
"""Verify an OCaml 4.0.2 Mesa dump and generate embedded zstd assets.

Usage: embed.py --network mainnet <dump>/circuit-blobs/4.0.2mainnet
The dump may contain symlinks. The committed SHA-256 list is the authority.
"""
import argparse
import hashlib
from pathlib import Path
import subprocess

ROOT = Path(__file__).resolve().parents[2]
NETWORKS = ("devnet", "mainnet")
ASSETS = ROOT / "crates/ledger/src/proofs/data/circuits"
MODULE = ROOT / "crates/ledger/src/proofs/embedded_circuits.rs"


def manifest(network):
    pins = ROOT / f"tools/mesa-circuits/{network}-blobs.sha256"
    entries = [line.split() for line in pins.read_text().splitlines()]
    if len(entries) != 24 or len({name for _, name in entries}) != 24:
        raise SystemExit("expected exactly 24 distinct SHA-256 entries")
    for digest, name in entries:
        if len(digest) != 64 or any(c not in "0123456789abcdef" for c in digest):
            raise SystemExit(f"invalid SHA-256: {name}")
        if Path(name).name != name or name in (".", ".."):
            raise SystemExit(f"invalid circuit name: {name}")
    return entries


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--network", choices=NETWORKS, required=True)
    parser.add_argument("source", type=Path)
    args = parser.parse_args()
    source = args.source
    entries = manifest(args.network)
    out = ASSETS / f"4.0.2{args.network}"
    if {p.name for p in source.iterdir()} != {name for _, name in entries}:
        raise SystemExit("dump names do not match the SHA-256 manifest")
    verified = []
    for digest, name in entries:
        path = (source / name).resolve(strict=True)
        if hashlib.sha256(path.read_bytes()).hexdigest() != digest:
            raise SystemExit(f"SHA-256 mismatch: {name}")
        verified.append((digest, name, path))
    out.mkdir(parents=True, exist_ok=True)
    if {p.name for p in out.iterdir()} - {name + ".zst" for _, name, _ in verified}:
        raise SystemExit("unexpected file in embedded circuit directory")
    for digest, name, path in verified:
        compressed = subprocess.run(
            ["zstd", "-19", "-q", "-c", str(path)], check=True, capture_output=True
        ).stdout
        restored = subprocess.run(
            ["zstd", "-d", "-q", "-c"],
            input=compressed,
            check=True,
            capture_output=True,
        ).stdout
        if hashlib.sha256(restored).hexdigest() != digest:
            raise SystemExit(f"compressed round trip failed: {name}")
        (out / (name + ".zst")).write_bytes(compressed)
    # Check both sets before emitting their shared lookup table. This also
    # catches stale frames after a manifest edit, even for the other network.
    for network in NETWORKS:
        for digest, name in manifest(network):
            restored = subprocess.run(
                ["zstd", "-d", "-q", "-c", str(ASSETS / f"4.0.2{network}" / (name + ".zst"))],
                check=True, capture_output=True,
            ).stdout
            if hashlib.sha256(restored).hexdigest() != digest:
                raise SystemExit(f"embedded SHA-256 mismatch: {network}/{name}")
    lines = [
        "//! OCaml 4.0.2 Mesa circuit blobs; generated by tools/mesa-circuits/embed.py.",
        "//! Digests are from tools/mesa-circuits/{devnet,mainnet}-blobs.sha256.",
        "",
        "pub(super) struct Circuit {",
        "    pub sha256: &'static str,",
        '    #[cfg(feature = "embedded-circuits")]',
        "    pub compressed: &'static [u8],",
        "}",
        "",
        "pub(super) fn get(directory: &str, name: &str) -> Option<Circuit> {",
        "    match (directory, name) {",
    ]
    for network in NETWORKS:
        directory = f"4.0.2{network}"
        for digest, name in manifest(network):
            lines += [
                f'        ("{directory}", "{name}") => Some(Circuit {{',
                f'            sha256: "{digest}",',
                '            #[cfg(feature = "embedded-circuits")]',
                f'            compressed: include_bytes!("data/circuits/{directory}/{name}.zst"),',
                "        }),",
            ]
    lines += ["        _ => None,", "    }", "}", ""]
    MODULE.write_text("\n".join(lines))
    print(f"verified {len(verified)} {args.network} files; wrote {sum(p.stat().st_size for p in out.glob('*.zst'))} compressed bytes")


if __name__ == "__main__":
    main()
